static volatile HI_BOOL s_bThreadRun     = HI_FALSE;
static HI_BOOL          s_bThreadStarted = HI_FALSE;

/* 画一个字符：MSB = 最左像素 */
static HI_VOID osd_draw_char(HI_U16 *pBmp, HI_U32 x, HI_U32 y, char ch, HI_U16 color)
{
    HI_U32 row, bit;

    if (ch < 32 || ch > 126)
    {
        ch = '?';
    }
    for (row = 0; row < FONT_H; row++)
    {
        HI_U8 b = s_font8x16[ch - 32][row];
        HI_U16 *pLine = pBmp + (y + row) * OSD_W;

        for (bit = 0; bit < FONT_W; bit++)
        {
            if (b & (0x80 >> bit))
            {
                pLine[x + bit] = color;
            }
        }
    }
}

static HI_VOID osd_draw_text(HI_U16 *pBmp, HI_U32 x, HI_U32 y, const char *s, HI_U16 color)
{
    HI_U32 i;

    for (i = 0; s[i] != '\0'; i++)
    {
        if (x + FONT_W > OSD_W)
        {
            break;
        }
        osd_draw_char(pBmp, x, y, s[i], color);
        x += FONT_W;
    }
}

/* 重绘整块画布：第 1 行固定标题，第 2 行传入的时间串 */
static HI_VOID osd_paint(const char *pszTime)
{
    if (NULL == s_pBitmap)
    {
        return;
    }
    memset(s_pBitmap, 0, OSD_W * OSD_H * sizeof(HI_U16));   /* 全透明衬板 */
    osd_draw_text(s_pBitmap, 4, 4,  "HI3516DV300 OSD", OSD_TEXT_COLOR);
    osd_draw_text(s_pBitmap, 4, 20, pszTime,          OSD_TEXT_COLOR);
}

/* 把 CPU 侧位图提交给 RGN 硬件（内部写画布 + UpdateCanvas 交换） */
static HI_S32 osd_flush(HI_VOID)
{
    BITMAP_S stBitmap;

    if (NULL == s_pBitmap)
    {
        return HI_FAILURE;
    }
    memset(&stBitmap, 0, sizeof(stBitmap));
    stBitmap.enPixelFormat = PIXEL_FORMAT_ARGB_1555;
    stBitmap.u32Width      = OSD_W;
    stBitmap.u32Height     = OSD_H;
    stBitmap.pData         = s_pBitmap;

    return HI_MPI_RGN_SetBitMap(s_hHandle, &stBitmap);
}

/* 取系统时间格式化成 "YYYY-MM-DD HH:MM:SS" */
static HI_VOID osd_format_time(char *pszBuf, HI_U32 u32Len)
{
    time_t    tNow = time(HI_NULL);
    struct tm tmNow;

    localtime_r(&tNow, &tmNow);
    snprintf(pszBuf, u32Len, "%04d-%02d-%02d %02d:%02d:%02d",
             tmNow.tm_year + 1900, tmNow.tm_mon + 1, tmNow.tm_mday,
             tmNow.tm_hour, tmNow.tm_min, tmNow.tm_sec);
}

/* 睡到下一个整秒边界（而不是固定睡 1s），避免累积漂移把某秒跳掉 */
static HI_VOID osd_wait_next_second(HI_VOID)
{
    struct timeval tv;
    HI_U32 u32SleepUs;

    gettimeofday(&tv, HI_NULL);
    u32SleepUs = (HI_U32)(1000000 - tv.tv_usec);
    if (0 == u32SleepUs || u32SleepUs > 1000000)
    {
        u32SleepUs = 1000000;
    }
    (HI_VOID)usleep(u32SleepUs);
}

static HI_VOID *osd_refresh_proc(HI_VOID *pArg)
{
    char   szTime[32];
    HI_S32 s32Ret;

    (HI_VOID)pArg;
    while (s_bThreadRun)
    {
        osd_format_time(szTime, sizeof(szTime));
        osd_paint(szTime);
        s32Ret = osd_flush();
        if (HI_SUCCESS != s32Ret)
        {
            SAMPLE_PRT("OSD: refresh SetBitMap failed, ret=%#x\n", s32Ret);
        }
        osd_wait_next_second();
    }
    return HI_NULL;
}

HI_S32 osd_test_start(HI_S32 s32VencChn)
{
    HI_S32          s32Ret;
    RGN_ATTR_S      stRgnAttr;
    RGN_CHN_ATTR_S  stChnAttr;
    MPP_CHN_S       stChn;
    char            szTime[32];
    pthread_attr_t  stAttr;

    /* 1. 创建 overlay 区域（u32CanvasNum=2：双缓冲，防刷新撕裂） */
    memset(&stRgnAttr, 0, sizeof(stRgnAttr));
    stRgnAttr.enType                              = OVERLAY_RGN;
    stRgnAttr.unAttr.stOverlay.enPixelFmt         = PIXEL_FORMAT_ARGB_1555;
    stRgnAttr.unAttr.stOverlay.stSize.u32Width    = OSD_W;
    stRgnAttr.unAttr.stOverlay.stSize.u32Height   = OSD_H;
    stRgnAttr.unAttr.stOverlay.u32BgColor         = 0x000000;   /* 衬板颜色：黑 */
    stRgnAttr.unAttr.stOverlay.u32CanvasNum       = 2;

    s32Ret = HI_MPI_RGN_Create(s_hHandle, &stRgnAttr);
    if (HI_SUCCESS != s32Ret)
    {
        SAMPLE_PRT("OSD: HI_MPI_RGN_Create failed, ret=%#x\n", s32Ret);
        return s32Ret;
    }
    s_bCreated = HI_TRUE;
    printf("OSD: RGN create OK (%dx%d ARGB1555, canvas=2)\n", OSD_W, OSD_H);

    /* 2. 位图：堆分配（不放 BSS）+ 首次渲染 */
    s_pBitmap = (HI_U16 *)malloc(OSD_W * OSD_H * sizeof(HI_U16));
    if (NULL == s_pBitmap)
    {
        SAMPLE_PRT("OSD: malloc bitmap failed\n");
        goto ERR_DESTROY;
    }
    osd_format_time(szTime, sizeof(szTime));
    osd_paint(szTime);

    s32Ret = osd_flush();
    if (HI_SUCCESS != s32Ret)
    {
        SAMPLE_PRT("OSD: HI_MPI_RGN_SetBitMap failed, ret=%#x\n", s32Ret);
        goto ERR_FREE;
    }
    printf("OSD: first bitmap OK, time=\"%s\"\n", szTime);

    /* 3. 挂到 VENC 主通道 */
    memset(&stChnAttr, 0, sizeof(stChnAttr));
    stChnAttr.bShow                                 = HI_TRUE;
    stChnAttr.enType                                = OVERLAY_RGN;
    stChnAttr.unChnAttr.stOverlayChn.stPoint.s32X   = OSD_X;
    stChnAttr.unChnAttr.stOverlayChn.stPoint.s32Y   = OSD_Y;
    stChnAttr.unChnAttr.stOverlayChn.u32FgAlpha     = OSD_FG_ALPHA;
    stChnAttr.unChnAttr.stOverlayChn.u32BgAlpha     = OSD_BG_ALPHA;
    stChnAttr.unChnAttr.stOverlayChn.u32Layer       = 2;   /* higher than DRAW layer 1 */
    stChnAttr.unChnAttr.stOverlayChn.stQpInfo.bAbsQp       = HI_FALSE;
    stChnAttr.unChnAttr.stOverlayChn.stQpInfo.bQpDisable   = HI_FALSE;
    stChnAttr.unChnAttr.stOverlayChn.stInvertColor.bInvColEn = HI_FALSE;

    stChn.enModId  = HI_ID_VENC;
    stChn.s32DevId = 0;
    stChn.s32ChnId = s32VencChn;

    s32Ret = HI_MPI_RGN_AttachToChn(s_hHandle, &stChn, &stChnAttr);
    if (HI_SUCCESS != s32Ret)
    {
        SAMPLE_PRT("OSD: HI_MPI_RGN_AttachToChn failed, ret=%#x (chn=%d)\n",
                   s32Ret, s32VencChn);
        goto ERR_FREE;
    }
    s_bAttached = HI_TRUE;
    printf("OSD: attach to VENC chn%d OK at (%d,%d)\n", s32VencChn, OSD_X, OSD_Y);

#if OSD_REFRESH_ENABLE
    /* 4. 起刷新线程：每秒重绘一次时间戳 */
    s_bThreadRun = HI_TRUE;
    pthread_attr_init(&stAttr);
    pthread_attr_setstacksize(&stAttr, OSD_THREAD_STACK);
    if (0 != pthread_create(&s_thread, &stAttr, osd_refresh_proc, HI_NULL))
    {
        SAMPLE_PRT("OSD: create refresh thread failed, OSD stays static\n");
        s_bThreadRun = HI_FALSE;
    }
    else
    {
        s_bThreadStarted = HI_TRUE;
        printf("OSD: refresh thread started (1s interval)\n");
    }
    pthread_attr_destroy(&stAttr);
#endif

    return HI_SUCCESS;

ERR_FREE:
    free(s_pBitmap);
    s_pBitmap = NULL;
ERR_DESTROY:
    HI_MPI_RGN_Destroy(s_hHandle);
    s_bCreated = HI_FALSE;
    return HI_FAILURE;
}

HI_VOID osd_test_stop(HI_VOID)
{
    MPP_CHN_S stChn;

    if (HI_TRUE == s_bThreadStarted)
    {
        s_bThreadRun = HI_FALSE;
        (HI_VOID)pthread_join(s_thread, HI_NULL);   /* 等线程退出再拆资源 */
        s_bThreadStarted = HI_FALSE;
    }

    stChn.enModId  = HI_ID_VENC;
    stChn.s32DevId = 0;
    stChn.s32ChnId = 0;

    if (HI_TRUE == s_bAttached)
    {
        HI_MPI_RGN_DetachFromChn(s_hHandle, &stChn);
        s_bAttached = HI_FALSE;
    }
    if (HI_TRUE == s_bCreated)
    {
        HI_MPI_RGN_Destroy(s_hHandle);
        s_bCreated = HI_FALSE;
    }
    if (NULL != s_pBitmap)
    {
        free(s_pBitmap);
        s_pBitmap = NULL;
    }
}
